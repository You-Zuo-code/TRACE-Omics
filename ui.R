byod_layer_ui <- function(i, default_type, optional = FALSE) {
  p <- BYOD_OMICS_TYPES[[default_type]]
  id <- function(x) paste0("byod_", x, i)
  tagList(
    fileInput(id("expr"),
              sprintf("Layer %d matrix%s (CSV/TSV)", i, if (optional) " — optional" else ""),
              accept = c(".csv", ".tsv", ".txt", ".gz")),

    conditionalPanel(
      if (optional) sprintf("output.byod_layer_shown%d == 'yes'", i) else "true",
      selectInput(id("type"), "Assay type", BYOD_OMICS_CHOICES, selected = default_type),
      layout_columns(col_widths = c(6, 6), fill = FALSE,
        textInput(id("name"), "Layer name", p$name),
        textInput(id("unit"), "Unit", p$unit)),
      selectInput(id("norm"), "Normalization", BYOD_NORM_METHODS, selected = p$norm),
      tags$details(
        tags$summary("Species annotation & gene sets"),
        helpText("Built-in annotation is available for human, pig, mouse and rat. Expression row names stay unchanged."),
        selectInput(id("idtype"), "Input identifier type", c("Gene symbol" = "symbol",
          "Ensembl gene ID" = "ensembl", "Entrez Gene ID" = "entrez",
          "UniProt accession (automatic lookup: human only)" = "uniprot", "Other / custom feature ID" = "other")),
        selectInput(id("idspace"), "Input identifiers belong to", c("The source organism" = "native",
          "Human — already mapped upstream" = "human")),
        selectInput(id("annotation"), "Gene annotation target", c("Human gene sets / ortholog comparison" = "human",
          "Native IDs only (custom GMT optional)" = "none")),
        conditionalPanel(sprintf("input.%s == 'human'", id("annotation")),
          selectInput(id("mapmode"), "Mapping source",
            c("Use built-in mapping (recommended)" = "builtin", "Upload a custom mapping" = "custom"),
            selected = "builtin")),
        uiOutput(id("mapping_hint")),
        conditionalPanel(sprintf("input.%s == 'human' && input.%s == 'custom'", id("annotation"), id("mapmode")),
          fileInput(id("mapping"), "Custom mapping to human symbols (CSV/TSV)", accept = c(".csv", ".tsv")),
          helpText("Columns: source_id, target_id. target_id is a human gene symbol. Only unique relationships are used."),
          textInput(id("mapsource"), "Custom mapping source and version", "")),
        tags$details(
          tags$summary("Advanced: custom gene sets"),
          checkboxInput(id("usegmt"), "Use a custom GMT", FALSE),
          conditionalPanel(sprintf("input.%s == true", id("usegmt")),
            fileInput(id("gmt"), "GMT in original feature IDs", accept = ".gmt"),
            helpText("Tab-separated set name, description and feature IDs. Select Custom GMT in pathway analyses.")))),
      uiOutput(paste0("byod_layer_hint", i)),
      tags$hr(class = "my-2")))
}

